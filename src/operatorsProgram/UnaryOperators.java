package operatorsProgram;

public class UnaryOperators {
    public static void main(String[] args) {

        int a = 5;
        boolean flag = true;

        System.out.println(+a);
        System.out.println(-a);

        System.out.println(++a);
        System.out.println(--a);

        System.out.println(!flag);
    }
}